import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'src'))

import matplotlib.pyplot as plt
import numpy as np
from scipy.integrate import solve_ivp
from scipy.signal import find_peaks

import network
import settings
from meng_command import MengCommand


"""Test Meng et al.'s AVA-master dynamics on the unchanged 102-cell network.

AVA activity is prescribed as a tonic → phasic → tonic protocol. IAVA is the
phasic component, while IAVB is generated by the paper's fast-inhibitory,
slow-excitatory AVA→AVB model. Only these two applied-current amplitudes change;
the motor-network topology and conductances remain at the shared baseline.
"""

MEDIA_DIR = os.path.join(os.path.dirname(__file__), '..', 'media')
DEFAULT_COMMAND = MengCommand()
DEFAULT_PULSE = (15000.0, 25000.0)
DEFAULT_PHASES = (
    ('tonic / forward', 0.0, 15000.0),
    ('phasic AVA / backward', 15000.0, 25000.0),
    ('recovery / forward', 25000.0, 45000.0),
)


def ava_protocol(t_ms, command=DEFAULT_COMMAND, pulse=DEFAULT_PULSE):
    """Tonic AVA activity with one imposed phasic event."""
    return command.ava_phasic if pulse[0] <= t_ms < pulse[1] else command.ava_tonic


def _joint_rhs(t_ms, state, command, pulse):
    network_state = state[:-1]
    slow_state = state[-1]
    ava = ava_protocol(t_ms, command, pulse)
    iava, iavb = command.currents(ava, slow_state)
    current = network.drive_vector(IAVA=iava, IAVB=iavb)
    network_derivative = network.rhs_vw(network_state, current)
    slow_derivative = command.slow_derivative_per_ms(ava, slow_state)
    return np.concatenate([network_derivative, [slow_derivative]])


def simulate(
    command=DEFAULT_COMMAND,
    pulse=DEFAULT_PULSE,
    tf=45000.0,
    dt=20.0,
    conductances=None,
    k_syn=None,
):
    """Integrate the command filter and network as one ODE system.

    ``conductances`` may override one or more of ``G_syne``, ``G_syni``, and
    ``G_gap`` for sensitivity experiments. Connectivity remains unchanged.
    """
    settings.reset_defaults()
    network.configure()
    if k_syn is not None:
        settings.k_syn = float(k_syn)
    if conductances is not None:
        allowed = {'G_syne', 'G_syni', 'G_gap'}
        unknown = set(conductances) - allowed
        if unknown:
            raise ValueError(f'Unknown conductance overrides: {sorted(unknown)}')
        for name, value in conductances.items():
            setattr(settings, name, float(value))

    t_eval = np.arange(0.0, tf + 0.5 * dt, dt)
    initial = np.concatenate([network.reduced_rest_state(), [command.slow_tonic]])
    solution = solve_ivp(
        lambda t, x: _joint_rhs(t, x, command, pulse),
        (0.0, tf),
        initial,
        method='BDF',
        t_eval=t_eval,
        max_step=50.0,
        rtol=1e-5,
        atol=1e-7,
    )
    if not solution.success:
        raise RuntimeError(solution.message)

    voltage = solution.y[:settings.numCells]
    slow = solution.y[-1]
    ava = np.array([ava_protocol(t, command, pulse) for t in solution.t])
    iava, iavb = command.currents(ava, slow)
    return solution.t, voltage, ava, slow, iava, iavb


def _wave_gradient(t, voltage, start, end, skip=1000.0):
    """Dorsal-muscle phase slope; positive is anterior→posterior."""
    dorsal = np.where(network.classes == 8)[0]
    mask = (t >= start + skip) & (t < end)
    traces = voltage[dorsal][:, mask]
    traces = traces - traces.mean(axis=1, keepdims=True)
    dt = float(np.median(np.diff(t)))
    peaks, _ = find_peaks(traces[0], prominence=8.0)
    if len(peaks) < 3:
        return np.nan
    period = float(np.median(np.diff(peaks)) * dt)
    max_lag = int(period / (2.0 * dt))
    center = traces.shape[1] - 1
    lags = []
    for trace in traces:
        corr = np.correlate(trace, traces[0], mode='full')
        window = corr[center - max_lag:center + max_lag + 1]
        lags.append((np.argmax(window) - max_lag) * dt)
    return float(np.polyfit(np.arange(len(lags)), lags, 1)[0])


def plot(
    t,
    voltage,
    ava,
    slow,
    iava,
    iavb,
    command=DEFAULT_COMMAND,
    pulse=DEFAULT_PULSE,
    save=True,
):
    """Create a shareable command-and-network comparison figure."""
    time_s = t / 1000.0
    dorsal = np.where(network.classes == 8)[0]
    ventral = np.where(network.classes == 9)[0]

    fig, axes = plt.subplots(
        4, 1, figsize=(13, 10), sharex=True,
        gridspec_kw={'height_ratios': [0.65, 0.65, 1.0, 1.0]},
    )
    fig.suptitle(
        'AVA-master command on the unchanged 102-cell locomotor network\n'
        r'Meng WT: $a=-0.51$, $b=0.02$, $\tau=3.5$ s; '
        f'network $k_{{syn}}={settings.k_syn}$',
        y=0.995,
    )
    axes[0].plot(time_s, ava, color='darkred', label=r'$x_{\rm AVA}$')
    axes[0].plot(time_s, slow / command.tau_s, color='darkorange',
                 label=r'$y/\tau$ (slow AVA history)')
    axes[0].set_ylabel('activity\n(a.u.)')
    axes[0].legend(loc='upper right', ncol=2, fontsize=8)

    axes[1].plot(time_s, iava, color='crimson', label=r'$I_{\rm AVA}$')
    axes[1].plot(time_s, iavb, color='steelblue', label=r'$I_{\rm AVB}$')
    axes[1].set_ylabel('motor drive\n(pA)')
    axes[1].legend(loc='upper right', ncol=2, fontsize=8)

    for axis, indices, label in (
        (axes[2], dorsal, 'Dorsal muscle'),
        (axes[3], ventral, 'Ventral muscle'),
    ):
        image = axis.imshow(
            voltage[indices],
            aspect='auto',
            origin='upper',
            extent=[time_s[0], time_s[-1], len(indices), 0],
            cmap='viridis',
            vmin=settings.L,
            vmax=settings.H,
        )
        axis.set_ylabel(f'{label}\n(ant → post)')
        fig.colorbar(image, ax=axis, label='mV', pad=0.01)

    for axis in axes:
        axis.axvspan(pulse[0] / 1000.0, pulse[1] / 1000.0,
                     color='crimson', alpha=0.08)
    axes[3].set_xlabel('time (s)')
    fig.tight_layout(rect=(0.0, 0.0, 1.0, 0.95))

    if save:
        path = os.path.join(MEDIA_DIR, 'network_ava_master_command.png')
        fig.savefig(path, dpi=150)
        print(f'Saved → {path}')
    return fig


def run(save=True):
    t, voltage, ava, slow, iava, iavb = simulate()
    print('AVA-master experiment (Meng wild-type command dynamics):')
    print(f'  tonic currents: IAVA={iava[0]:.2f}, IAVB={iavb[0]:.2f} pA')
    pulse_mask = (t >= DEFAULT_PULSE[0]) & (t < DEFAULT_PULSE[1])
    print(
        f'  AVA event: IAVA={np.max(iava[pulse_mask]):.2f} pA, '
        f'IAVB={np.min(iavb[pulse_mask]):.2f}–{np.max(iavb[pulse_mask]):.2f} pA'
    )
    for label, start, end in DEFAULT_PHASES:
        slope = _wave_gradient(t, voltage, start, end)
        if not np.isfinite(slope):
            direction = 'no clean oscillation'
        else:
            direction = 'A→P' if slope > 0 else 'P→A'
        print(f'  {label:24s}: {slope:+6.1f} ms/row ({direction})')
    plot(t, voltage, ava, slow, iava, iavb, pulse=DEFAULT_PULSE, save=save)
    return t, voltage, ava, slow, iava, iavb


if __name__ == '__main__':
    run()
